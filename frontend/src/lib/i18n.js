export function t(key) {
  const locale = useLocaleStore.getState().locale
  return DICTIONARY[locale]?.[key] || DICTIONARY.az[key] || key
}

export function useT() {
  const locale = useLocaleStore((s) => s.locale)
  return (key) => DICTIONARY[locale]?.[key] || DICTIONARY.az[key] || key
}

// DB-dən gələn obyektlərdə (məhsul/kateqoriya/restoran) cari dilə uyğun sahəni seçir,
// tərcümə boşdursa AZ (əsas) sahəyə geri qayıdır.
export function useLocalize() {
  const locale = useLocaleStore((s) => s.locale)
  return (entity, field) => {
    if (!entity) return ''
    if (locale === 'az') return entity[field] || ''
    return entity[`${field}_${locale}`] || entity[field] || ''
  }
}
